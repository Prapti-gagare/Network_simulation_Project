// LLL of host i: copy LLL in to LLL out(towords the LAN)

void LLL_send(int i)
{
    if(LLL_up[i].d[1][0] != 0 && LLL_down[i].d[0][0]==0)
{
memcpy(LLL_down[i].d[0],LLL_up[i].d[1],LLL_up[i].d[1][0]+1);
LLL_up[i].d[1][0]=0;
}
}

//LLL of host i:packet came from the LAN,check SMAC address

void LLL_receive(int i)
{
    char *p=LLL_down[i].d[1];
    if(p[0] == 0) return;
    if(p[3] == h[i].net_id && p[4] ==h[i].machine_id && p[5] == h[i].smac_id)
    {
        memcpy(LLL_up[i].d[0],p,p[0]+1);
    }
    else{
        p[0]=0;
    }
}

