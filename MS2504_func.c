//no fixed order : puts the host numbers in a random order
void random_order(int order[])
{
    int i,j,t;
    for(i=0;i<N_hosts;i++)
    order[i]=i;
for(i=N_hosts - 1;i>0;i--)
{
    j=random_number() % (i+1);
    t=order[i];
    order[i]=order[j];
    order[j]=t;
}
}

